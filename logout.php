<?php

declare(strict_types=1);

/**
 * =========================================================
 * GREEN HARVEST - CUSTOMER LOGOUT
 * =========================================================
 *
 * Logs out the current user and returns them
 * to the public homepage.
 * =========================================================
 */

require_once __DIR__ . '/includes/bootstrap.php';


/*
|--------------------------------------------------------------------------
| Logout
|--------------------------------------------------------------------------
*/

if (isLoggedIn()) {
    logoutUser();
}


/*
|--------------------------------------------------------------------------
| Redirect
|--------------------------------------------------------------------------
*/

redirectTo('index.php');